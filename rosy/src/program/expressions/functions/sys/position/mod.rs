//! # POSITION Function
//!
//! Returns the 1-based index of the first occurrence of a substring,
//! or 0 if not found. Matches COSY INFINITY behavior.
//!
//! ## Syntax
//!
//! ```text
//! POSITION(haystack, needle)
//! ```
//!
//! ## Type Compatibility
//!
//! | Haystack | Needle | Result |
//! |----------|--------|--------|
//! | ST | ST | RE |

