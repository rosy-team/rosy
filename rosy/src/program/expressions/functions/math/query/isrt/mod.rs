//! # ISRT Function (Inverse Square Root)
//!
//! Computes x^(-1/2) = 1/sqrt(x).
//!
//! ## Syntax
//!
//! ```text
//! ISRT(expr)
//! ```
//!
//! ## Type Compatibility
//!
//! | Input | Result |
//! |-------|--------|
//! | RE | RE |
//! | VE | VE |
//! | DA | DA |
//!
