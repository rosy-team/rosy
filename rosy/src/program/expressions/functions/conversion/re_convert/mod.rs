//! # RE() — Real Number Conversion
//!
//! Converts a value to a real number (`RE`).
//!
//! ## Syntax
//!
//! ```text
//! RE(expr)
//! ```
//!
//! ## Type Compatibility
//!
//! | Input | Result |
//! |-------|--------|
//! | RE    | RE     |
//! | ST    | RE     |
//! | CM    | RE     |
//! | VE    | RE     |
//! | DA    | RE     |
//!
//! ## Rosy Example
//! ```text
#![doc = include_str!("test.rosy")]
//! ```
//! **Output**:
//! ```text
#![doc = include_str!("rosy_output.txt")]
//! ```
//! ## COSY INFINITY Example
//! ```text
#![doc = include_str!("test.fox")]
//! ```
//! **Output**:
//! ```text
#![doc = include_str!("cosy_output.txt")]
//! ```

